@slow
def test_two_column_pdf_reading_order_is_column_aware(parser):
    """Layout-aware reading order should keep each column's content
    together (all of the left column before all of the right column),
    not interleave by raw top-to-bottom position across both columns."""
    doc, _ = _parse(parser, "two_column.pdf")
    _assert_healthy(doc, expect_status="complete")
    left_indices = [i for i, c in enumerate(doc.chunks) if "LEFT COLUMN" in c.text]
    right_indices = [i for i, c in enumerate(doc.chunks) if "RIGHT COLUMN" in c.text]
    assert left_indices and right_indices
    assert max(left_indices) < min(right_indices), (
        "expected all left-column chunks to precede all right-column chunks in reading order "
        f"(left={left_indices}, right={right_indices}) -- Docling's layout model may have treated "
        "this crude synthetic layout as single-flow rather than genuine columns"
    )


