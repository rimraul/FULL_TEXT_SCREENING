def _make_e2e_request(output_dir: Path, pdf_path_or_items, **config_overrides):
    from ft_screening.schema import CriteriaSet, CriterionSpec, ScreeningConfig, ScreeningItem, ScreeningRequest

    criteria_set = CriteriaSet(
        criteria_set_id="cs-1", version="1",
        criteria=[
            CriterionSpec(
                criterion_id="population", version="1", eligibility_requirement="adult humans",
                missing_evidence_policy="review", exclusion_reason_code="wrong_population",
                exclusion_reason_label="Wrong population", priority=1,
            )
        ],
    )
    defaults = dict(
        parser_name="docling", parser_version="2.61.2", chunker_version="1",
        parser_options=DoclingDocumentParser.recommended_parser_options(),
        retriever_name="fake", retriever_config_version="1",
        adjudicator_provider="fake", adjudicator_model="fake-1",
        model_config_id="cfg-1", prompt_template_version="1", output_schema_version="1",
        aggregation_policy_version="1",
    )
    defaults.update(config_overrides)
    config = ScreeningConfig(**defaults)
    if isinstance(pdf_path_or_items, Path):
        items = [ScreeningItem(document_id="d1", report_id="r1", pdf_path=pdf_path_or_items)]
    else:
        items = pdf_path_or_items
    return ScreeningRequest(items=items, criteria_set=criteria_set, config=config, output_dir=output_dir)


def _make_e2e_components(output_dir: Path, real_parser: DoclingDocumentParser):
    from ft_screening.components import Components
    from ft_screening.fakes import FakeCriterionAdjudicator, FakeEvidenceRetriever
    from ft_screening.store import FileScreeningStore

    return Components(
        parser=real_parser, retriever=FakeEvidenceRetriever(), adjudicator=FakeCriterionAdjudicator(),
        store=FileScreeningStore(output_dir=output_dir),
    )


@slow
def test_post_conversion_build_failure_is_sanitized_end_to_end(tmp_path):
    """codex_code_review_afeba09.md finding 2: the status check and
    _build_parsed_document() call happened OUTSIDE any try/except --
    Codex's own repro was a converter returning ConversionStatus.SUCCESS
    whose document raised WHILE iterate_items() executed. Reproduced here
    with a purpose-built fake converter/result (no real Docling model
    loading needed -- the fake parser's artifact-resolution state is
    populated directly, so this test is fast despite being marked slow
    for its docling.datamodel import)."""
    from docling.datamodel.base_models import ConversionStatus

    from ft_screening import docling_artifacts
    from ft_screening.orchestrator import _run_ft_screening

    class _RaisingDoclingDocument:
        def iterate_items(self):
            raise RuntimeError("SECRET-POST-CONVERT-sentinel at /private/path")
            yield  # pragma: no cover -- unreachable; makes this a generator function

    class _FakeSuccessResult:
        status = ConversionStatus.SUCCESS
        document = _RaisingDoclingDocument()
        pages: list = []
        errors: list = []

    class _FakeConverter:
        def convert(self, path):
            return _FakeSuccessResult()

    fake_parser = DoclingDocumentParser()
    fake_parser._resolved_artifacts_path = Path("unused-for-this-test")
    fake_parser._validated_digest = docling_artifacts.load_manifest()["expected_tree_digest"]
    fake_parser._converters[(True, True)] = _FakeConverter()

    output_dir = tmp_path / "outputs"
    request = _make_e2e_request(output_dir, _fixture("simple_two_page.pdf"))
    components = _make_e2e_components(output_dir, fake_parser)
    result = _run_ft_screening(request, components)
    item = result.items[0]
    assert item.execution_status == "processing_failed"
    _assert_no_leak([e.message for e in item.errors], "SECRET-POST-CONVERT-sentinel", "/private/path")
    if item.coverage is not None:
        _assert_no_leak(item.coverage.warnings, "SECRET-POST-CONVERT-sentinel", "/private/path")


