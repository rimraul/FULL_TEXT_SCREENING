def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _fixture(name: str) -> Path:
    path = PDFS_DIR / name
    assert path.exists(), f"missing fixture {name} -- run tests/fixtures/generate_pdfs.py"
    return path


@pytest.fixture(scope="module")
def parser() -> DoclingDocumentParser:
    """ONE shared instance for the whole module -- Docling's OCR/layout
    model warmup (~45-150s) is a one-time cost per (do_ocr,
    do_table_structure) combination; re-creating it per test would make
    this module's runtime dominated by redundant warmup instead of actual
    conversion work."""
    return DoclingDocumentParser()


def _parse(parser: DoclingDocumentParser, name: str, **parser_options) -> tuple:
    path = _fixture(name)
    sha = _sha256(path)
    # artifacts_manifest_digest became MANDATORY (codex_code_review_afeba09.md
    # finding 1) -- inject the correct one by default so every existing
    # caller of this helper keeps testing what it was actually testing,
    # unless a test explicitly overrides it (e.g. to test a mismatch).
    if "artifacts_manifest_digest" not in parser_options:
        parser_options = DoclingDocumentParser.recommended_parser_options(**parser_options)
    doc = parser.parse(document_id="acceptance-doc", document_sha256=sha, pdf_path=path, parser_options=parser_options)
    return doc, sha


def _assert_healthy(doc, *, expect_status: str = None) -> None:
    """codex_code_review_1578af2.md finding 4: several tests previously
    passed even when the ENTIRE Docling backend was broken (e.g. during a
    failed model download), because they only checked properties that a
    totally-failed parse ALSO happens to satisfy (ocr_used=False, zero
    characters, no chunks). Call this FIRST in any positive-path test."""
    assert doc.coverage.status != "failed", (
        f"parser backend appears broken -- coverage.status == 'failed', warnings={doc.coverage.warnings!r}"
    )
    if expect_status is not None:
        assert doc.coverage.status == expect_status


