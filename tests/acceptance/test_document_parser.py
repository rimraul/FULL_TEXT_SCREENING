def _assert_offsets_consistent(doc) -> None:
    """Chunks are produced in document order with a fixed "\\n\\n"
    separator between them (document.py's own convention) -- each
    chunk's start_char should exactly equal the previous chunk's end_char
    plus that separator's length, not merely "close enough"."""
    previous_end = None
    for chunk in doc.chunks:
        assert chunk.end_char >= chunk.start_char
        assert chunk.end_char <= doc.coverage.extracted_characters
        if previous_end is not None:
            assert chunk.start_char == previous_end + 2  # len("\n\n")
        previous_end = chunk.end_char


@slow
def test_simple_two_page_parses_correctly(parser):
    doc, sha = _parse(parser, "simple_two_page.pdf")
    expected = MANIFEST["simple_two_page.pdf"]["expected"]
    _assert_healthy(doc, expect_status=expected["status"])
    assert doc.document_sha256 == sha
    assert doc.coverage.total_pages == expected["total_pages"]
    assert len(doc.chunks) >= expected["min_chunks"]
    sections = {c.section for c in doc.chunks}
    for expected_section in expected["sections_include"]:
        assert expected_section in sections
    _assert_offsets_consistent(doc)
    pages_used = {c.page for c in doc.chunks}
    assert pages_used <= {1, 2}


